  UNIQUE KEY uq_opportunities_public_id (public_id),
  KEY ix_opportunities_stage (stage),
  KEY ix_opportunities_close_date (close_date),
  KEY ix_opportunities_owner (owner_user_id),
  KEY ix_opportunities_account (account_id),

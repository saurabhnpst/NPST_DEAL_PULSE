CREATE TABLE IF NOT EXISTS opportunity_public_id_sequences (
  year SMALLINT UNSIGNED NOT NULL,
  last_number INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (year)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS opportunity_products (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  opportunity_id BIGINT UNSIGNED NOT NULL,
  product_slot TINYINT UNSIGNED NOT NULL COMMENT '1=productTsp ... 4=productTsp4',
  product_tsp VARCHAR(128) NOT NULL,
  modules JSON NOT NULL COMMENT 'Multi-select module names',
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  UNIQUE KEY uq_opportunity_products_slot (opportunity_id, product_slot),
  CONSTRAINT fk_opportunity_products_opp
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS opportunity_stage_history (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  opportunity_id BIGINT UNSIGNED NOT NULL,
  from_stage VARCHAR(32) NULL,
  to_stage VARCHAR(32) NOT NULL,
  changed_by_user_id BIGINT UNSIGNED NULL,
  changed_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  narrative TEXT NULL,
  lost_reason VARCHAR(64) NULL,
  lost_reason_remark VARCHAR(255) NULL,
  hold_reason VARCHAR(64) NULL,
  hold_details TEXT NULL,
  hold_until DATE NULL,
  hold_from_stage VARCHAR(32) NULL,
  early_close TINYINT(1) NOT NULL DEFAULT 0,
  override_reason VARCHAR(64) NULL,
  override_justification TEXT NULL,
  po_date DATE NULL,
  po_value DECIMAL(18, 2) NULL,
  closed_value DECIMAL(18, 2) NULL,
  project_start_actual DATE NULL,
  first_billing_date DATE NULL,
  first_billing_value DECIMAL(18, 2) NULL,
  PRIMARY KEY (id),
  KEY ix_stage_history_opp_changed (opportunity_id, changed_at),
  CONSTRAINT fk_stage_history_opp
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS opportunity_commercial_history (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  opportunity_id BIGINT UNSIGNED NOT NULL,
  version_label VARCHAR(128) NOT NULL,
  licence VARCHAR(32) NULL,
  milestones VARCHAR(32) NULL,
  amc_term VARCHAR(16) NULL,
  line_items JSON NOT NULL COMMENT '[{id,t,q,unit_price}] snapshot',
  created_by_user_id BIGINT UNSIGNED NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY ix_commercial_history_opp_created (opportunity_id, created_at),
  CONSTRAINT fk_commercial_history_opp
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS opportunity_activities (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  opportunity_id BIGINT UNSIGNED NOT NULL,
  activity_kind VARCHAR(16) NOT NULL COMMENT 'Call, Meeting, Email, Note, System',
  with_party VARCHAR(255) NULL,
  summary TEXT NOT NULL,
  actor_user_id BIGINT UNSIGNED NULL,
  actor_label VARCHAR(255) NULL,
  occurred_at DATETIME(6) NOT NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY ix_activities_opp_occurred (opportunity_id, occurred_at),
  CONSTRAINT fk_activities_opp
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS opportunity_domain_events (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  opportunity_id BIGINT UNSIGNED NOT NULL,
  event_type VARCHAR(64) NOT NULL,
  schema_version SMALLINT UNSIGNED NOT NULL DEFAULT 1,
  payload JSON NOT NULL COMMENT 'Full event envelope',
  correlation_id VARCHAR(64) NULL,
  occurred_at DATETIME(6) NOT NULL,
  published_at DATETIME(6) NULL COMMENT 'NULL = not yet sent to RabbitMQ',
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  PRIMARY KEY (id),
  KEY ix_domain_events_unpublished (published_at, id),
  KEY ix_domain_events_opp (opportunity_id),
  CONSTRAINT fk_domain_events_opp
    FOREIGN KEY (opportunity_id) REFERENCES opportunities (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

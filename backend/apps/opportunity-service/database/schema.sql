-- Opportunity Service schema (MySQL 8+), database: opportunity_db
-- Same SQL as src/migrations/1732200000000-OpportunitySchema.ts (a unit test keeps them in sync).
-- External ids (lead, account, users, documents) belong to other services: no cross-service foreign keys.

CREATE TABLE IF NOT EXISTS opportunities (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id VARCHAR(32) NOT NULL,
  lead_id BIGINT UNSIGNED NULL COMMENT 'Lead Service',
  account_id BIGINT UNSIGNED NULL COMMENT 'Lead/Account Service',
  account_name VARCHAR(255) NOT NULL,
  owner_user_id BIGINT UNSIGNED NULL COMMENT 'Auth Service',
  presales_user_id BIGINT UNSIGNED NULL COMMENT 'Auth Service',
  name VARCHAR(120) NOT NULL,
  record_type VARCHAR(16) NOT NULL DEFAULT 'TSP',
  lead_source VARCHAR(64) NULL,
  stage VARCHAR(32) NOT NULL,
  close_date DATE NOT NULL,
  followup_details TEXT NULL,
  updated_close_date DATE NULL,
  region VARCHAR(32) NULL,
  expected_po_date DATE NULL,
  current_volume VARCHAR(255) NULL,
  updated_expected_po_date DATE NULL,
  yearly_volume_projection DECIMAL(18, 0) NULL,
  project_start_expected DATE NULL,
  spoc_first_name VARCHAR(255) NULL,
  spoc_last_name VARCHAR(255) NULL,
  first_billing_expected DATE NULL,
  business_type VARCHAR(32) NULL COMMENT 'Type',
  territory VARCHAR(64) NULL,
  industry VARCHAR(64) NULL,
  sub_industry VARCHAR(128) NULL,
  merchant_category VARCHAR(255) NULL,
  account_size VARCHAR(16) NULL,
  industry_remark VARCHAR(255) NULL,
  product_remark VARCHAR(255) NULL,
  solution_type VARCHAR(32) NULL,
  hosting VARCHAR(32) NULL,
  service_model VARCHAR(32) NULL,
  product_owner VARCHAR(32) NULL,
  arr DECIMAL(18, 2) NOT NULL DEFAULT 0,
  one_time DECIMAL(18, 2) NOT NULL DEFAULT 0,
  updated_arr DECIMAL(18, 2) NULL,
  contract_years VARCHAR(4) NULL,
  billing_frequency VARCHAR(32) NULL,
  currency VARCHAR(8) NOT NULL DEFAULT 'INR',
  compelling_event VARCHAR(255) NULL,
  tender VARCHAR(32) NULL,
  year2 DECIMAL(18, 2) NULL,
  year3 DECIMAL(18, 2) NULL,
  year4 DECIMAL(18, 2) NULL,
  year5 DECIMAL(18, 2) NULL,
  transactions VARCHAR(255) NULL,
  opp_type VARCHAR(32) NULL,
  partner VARCHAR(8) NULL COMMENT 'Is Partner involved?',
  partner_name VARCHAR(255) NULL,
  competitors JSON NULL COMMENT 'Multi-select competition',
  competition_remarks VARCHAR(255) NULL,
  today VARCHAR(255) NULL COMMENT 'How do they do today?',
  implication VARCHAR(255) NULL,
  present_pain VARCHAR(255) NULL,
  pain_point VARCHAR(255) NULL,
  notes TEXT NULL,
  next_step TEXT NULL,
  fy27_q1 DECIMAL(18, 2) NULL,
  fy27_jul DECIMAL(18, 2) NULL,
  fy27_aug DECIMAL(18, 2) NULL,
  fy27_sep DECIMAL(18, 2) NULL,
  fy27_oct DECIMAL(18, 2) NULL,
  fy27_nov DECIMAL(18, 2) NULL,
  fy27_dec DECIMAL(18, 2) NULL,
  fy27_jan DECIMAL(18, 2) NULL,
  fy27_feb DECIMAL(18, 2) NULL,
  fy27_mar DECIMAL(18, 2) NULL,
  economic_buyer VARCHAR(255) NULL,
  champion TINYINT(1) NOT NULL DEFAULT 0,
  nda TINYINT(1) NOT NULL DEFAULT 0,
  champion_ok TINYINT(1) NOT NULL DEFAULT 0,
  strategy VARCHAR(255) NULL,
  req_received VARCHAR(8) NULL,
  presales_involved VARCHAR(8) NULL,
  presales_name VARCHAR(255) NULL,
  eb_aligned VARCHAR(8) NULL,
  success VARCHAR(255) NULL,
  eb_met DATE NULL,
  poc TINYINT(1) NOT NULL DEFAULT 0,
  demo_done TINYINT(1) NOT NULL DEFAULT 0,
  sow VARCHAR(8) NULL,
  proposal_date DATE NULL,
  criteria_known TINYINT(1) NOT NULL DEFAULT 0,
  latest_followup_date DATE NULL,
  criteria VARCHAR(255) NULL,
  contract_shared VARCHAR(8) NULL,
  contract_signed VARCHAR(8) NULL,
  discount VARCHAR(255) NULL,
  sign_date DATE NULL,
  commercials VARCHAR(8) NULL,
  bank_interview VARCHAR(8) NULL,
  documentation VARCHAR(8) NULL,
  bank_approval VARCHAR(8) NULL,
  uat_agreement VARCHAR(8) NULL,
  po_received VARCHAR(8) NULL,
  project_start_actual DATE NULL,
  first_billing_date DATE NULL,
  po_date DATE NULL,
  first_billing_value DECIMAL(18, 2) NULL,
  po_value DECIMAL(18, 2) NULL,
  closed_value DECIMAL(18, 2) NULL,
  lost_reason VARCHAR(64) NULL,
  lost_reason_remark VARCHAR(255) NULL,
  hold_reason VARCHAR(64) NULL,
  hold_details TEXT NULL,
  hold_until DATE NULL,
  hold_from_stage VARCHAR(32) NULL,
  hold_at DATETIME(6) NULL,
  reopened_at DATETIME(6) NULL,
  early_close TINYINT(1) NOT NULL DEFAULT 0,
  override_reason VARCHAR(64) NULL,
  override_justification TEXT NULL,
